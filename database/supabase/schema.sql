drop table if exists transactions cascade;
drop table if exists receipts     cascade;
drop table if exists payments     cascade;
drop table if exists bills        cascade;
drop table if exists meters       cascade;
drop table if exists accounts     cascade;
drop table if exists customers    cascade;
drop table if exists admins       cascade;

-- Customers (registered users). Login: email + password_hash.
create table customers (
  customer_id   bigint generated by default as identity primary key,
  name          varchar(120) not null,
  email         varchar(255) not null unique,
  phone         char(11)     not null check (phone ~ '^0[789][0-9]{9}$'),
  address       varchar(255),
  password_hash varchar(255) not null,            -- from password_hash(); never plain text
  created_at    timestamptz  not null default now()
);

-- Admins (back-office staff).
create table admins (
  admin_id      bigint generated by default as identity primary key,
  name          varchar(120) not null,
  email         varchar(255) not null unique,
  password_hash varchar(255) not null
);

-- Accounts (ERD: ACCOUNT).
create table accounts (
  account_id     bigint generated by default as identity primary key,
  customer_id    bigint not null references customers(customer_id) on delete cascade,
  account_number varchar(20) not null unique,
  account_status varchar(10) not null default 'active'
                 check (account_status in ('active', 'suspended', 'closed'))
);

-- Meters.
create table meters (
  meter_id     bigint generated by default as identity primary key,
  customer_id  bigint not null references customers(customer_id) on delete cascade,
  meter_number varchar(20) not null unique
);

-- Bills. period_start, period_end, units_kwh are NOT in the original ERD (added for the pages).
create table bills (
  bill_id       bigint generated by default as identity primary key,
  meter_id      bigint not null references meters(meter_id) on delete cascade,
  billing_date  date not null,
  due_date      date not null,
  period_start  date not null,
  period_end    date not null,
  units_kwh     numeric(10,2) not null default 0.00,
  amount        numeric(12,2) not null,
  bill_status   varchar(10) not null default 'pending'
                check (bill_status in ('pending', 'paid', 'overdue')),
  constraint chk_bills_amount check (amount >= 0),
  constraint chk_bills_units  check (units_kwh >= 0),
  constraint chk_bills_period check (period_end >= period_start)
);

-- Payments. gateway_transaction_id is the ERD's transaction_id, renamed (see MySQL schema).
create table payments (
  payment_id             bigint generated by default as identity primary key,
  bill_id                bigint not null references bills(bill_id) on delete restrict,
  amount                 numeric(12,2) not null check (amount >= 0),
  payment_date           timestamptz not null default now(),
  payment_status         varchar(10) not null default 'pending'
                         check (payment_status in ('pending', 'success', 'failed')),
  payment_method         varchar(15) not null check (payment_method in ('card', 'bank_transfer')),
  gateway_transaction_id varchar(40) unique
);

-- Receipts: one per payment.
create table receipts (
  receipt_id     bigint generated by default as identity primary key,
  payment_id     bigint not null unique references payments(payment_id) on delete cascade,
  receipt_number varchar(30) not null unique,
  issue_date     timestamptz not null default now()
);

-- Transactions: customer-facing history row (ERD: TRANSACTION).
create table transactions (
  transaction_id   bigint generated by default as identity primary key,
  customer_id      bigint not null references customers(customer_id) on delete restrict,
  payment_id       bigint not null references payments(payment_id) on delete restrict,
  transaction_date timestamptz not null default now(),
  amount           numeric(12,2) not null check (amount >= 0),
  status           varchar(10) not null check (status in ('pending', 'success', 'failed'))
);

-- Indexes on foreign keys (Postgres does not create these automatically).
create index idx_meters_customer        on meters(customer_id);
create index idx_accounts_customer      on accounts(customer_id);
create index idx_bills_meter_status     on bills(meter_id, bill_status);
create index idx_payments_bill          on payments(bill_id);
create index idx_payments_status_date   on payments(payment_status, payment_date);
create index idx_receipts_payment       on receipts(payment_id);
create index idx_transactions_customer  on transactions(customer_id, transaction_date);
create index idx_transactions_payment   on transactions(payment_id);

-- Supabase exposes the public schema over its API. Turn on Row Level Security
-- with no policies, so anon/authenticated API keys cannot read these tables.
-- PHP connects server-side with the database password, which is not affected by RLS.
alter table customers    enable row level security;
alter table admins       enable row level security;
alter table accounts     enable row level security;
alter table meters       enable row level security;
alter table bills        enable row level security;
alter table payments     enable row level security;
alter table receipts     enable row level security;
alter table transactions enable row level security;
